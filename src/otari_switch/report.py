VERDICT_LABEL = {"switch": "Switch", "switch_with_fallback": "Switch with fallback", "keep": "Keep frontier"}
VERDICT_ICON = {"switch": "✓", "switch_with_fallback": "↻", "keep": "–"}


def summarize(run: dict, monthly_calls: int) -> dict:
    sites = run["sites"]
    evaluated = [s for s in sites if s["candidates"]]
    counts = {v: sum(1 for s in evaluated if s["verdict"] == v) for v in VERDICT_LABEL}
    moved = counts["switch"] + counts["switch_with_fallback"]
    share = moved / len(evaluated) if evaluated else 0.0
    per_site_calls = monthly_calls / len(evaluated) if evaluated else 0
    savings, priced = 0.0, 0
    for s in evaluated:
        if s["chosen"] and s.get("frontier_cost_per_1k"):
            c = next(c for c in s["candidates"] if c["model"] == s["chosen"])
            if c["cost_per_1k"]:
                savings += (s["frontier_cost_per_1k"] - c["cost_per_1k"]) / 1000 * per_site_calls
                priced += 1
    tests = [c.get("tests_passed") for s in evaluated for c in s["candidates"] if c["model"] == s.get("chosen")]
    tests_state = "not run" if not tests or all(t is None for t in tests) else (
        "passed" if all(t is not False for t in tests) else "failed")
    return {
        "call_sites": len(sites), "evaluated": len(evaluated), **counts, "moved": moved,
        "open_share": round(share, 3), "monthly_calls_assumed": monthly_calls,
        "monthly_savings_usd": round(savings, 2) if priced else None, "tests": tests_state,
    }


def _money(v) -> str:
    if v is None:
        return "n/a"
    sign = "-" if v < 0 else ""
    v = abs(v)
    return f"{sign}${v:,.2f}" if v >= 1 else f"{sign}${v:,.4f}"


def markdown(run: dict) -> str:
    s = run["summary"]
    lines = [
        "## Otari Switch report", "",
        f"**{s['moved']} of {s['evaluated']} AI call sites can run on open-weight models through Otari.**", "",
        f"- Switch: {s['switch']} · Switch with fallback: {s['switch_with_fallback']} · Keep frontier: {s['keep']}",
        f"- Estimated monthly savings: {_money(s['monthly_savings_usd'])} "
        f"(assuming {s['monthly_calls_assumed']:,} calls a month)",
        f"- Repo tests on the chosen models: {s['tests']}",
        f"- Evaluation spend: {_money(run['spend_usd'])} of a {_money(run['budget_usd'])} cap"
        + (f" (billed to teammate `{run['budget']['end_user']}`)" if (run.get("budget") or {}).get("end_user") else ""),
        "", "| Call site | Today | Verdict | Chosen model | Score | Cost per 1k calls |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for site in run["sites"]:
        if not site["candidates"]:
            continue
        c = next((c for c in site["candidates"] if c["model"] == site["chosen"]), None)
        where = f"`{site['site']['file']}:{site['site']['line']}` {site['site']['function']}"
        verdict = f"{VERDICT_ICON[site['verdict']]} {VERDICT_LABEL[site['verdict']]}"
        if c:
            cost = f"{_money(c['cost_per_1k'])} vs {_money(site.get('frontier_cost_per_1k'))}"
            lines.append(f"| {where} | {site['frontier_model'] or 'dynamic'} | {verdict} | `{c['model']}` | "
                         f"{c['mean_score']:.1f}/5 | {cost} |")
        else:
            lines.append(f"| {where} | {site['frontier_model'] or 'dynamic'} | {verdict} | - | - | - |")
    lines += ["", "### Why"]
    for site in run["sites"]:
        if site["candidates"]:
            lines.append(f"- **{site['site']['function']}**: {site['reason']}")
    lines += ["", "### Routing policies", ""]
    for site in run["sites"]:
        p = site.get("policy")
        if p:
            chain = " → ".join(f"`{c['model']}`" for c in p["candidates"])
            lines.append(f"- `{p['name']}` ({p['env_var']}): {chain}")
    lic = run.get("licenses") or {}
    if lic:
        lines += ["", "### Model licences (model cards read through Otari's web fetch)", ""]
        for m, r in lic.items():
            label = {"open": "open", "restricted": "restricted terms", "unknown": "unverified",
                     "error": "not checked"}.get(r.get("status"), r.get("status"))
            src = f" ([model card]({r['source_url']}))" if r.get("source_url") and r.get("status") != "error" else ""
            lines.append(f"- `{m}`: {label}" + (f", `{r['license']}`" if r.get("license") else "") + src)
    if run.get("findings"):
        lines += ["", "### Findings"] + [f"- {f}" for f in run["findings"]]
    lines += ["", "### Rollback", "",
              "No code change needed: in the Otari dashboard, move the frontier model to the top of the policy.",
              "", "Every score links to its Otari request id in `.otari-switch/report.json`.",
              "", "_Generated by [Otari Switch](https://github.com/XSTRANGER-7/otari-switch) on Otari by Mozilla.ai._"]
    return "\n".join(lines) + "\n"


