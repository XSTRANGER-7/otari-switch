def write_all(work: Path, run: dict) -> dict[str, Path]:
    paths = {"json": work / "report.json", "md": work / "report.md", "html": work / "report.html"}
    paths["json"].write_text(json.dumps(run, indent=2), encoding="utf-8")
    paths["md"].write_text(markdown(run), encoding="utf-8")
    paths["html"].write_text(html_page(run), encoding="utf-8")
    return paths
